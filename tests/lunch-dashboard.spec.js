const { test, expect } = require('@playwright/test');

test('customer and kitchen share menus, quantities, pauses, tokens and reviews', async ({ page }, testInfo) => {
  test.setTimeout(120000);
  await page.clock.install({ time: new Date('2026-10-19T10:00:00') });
  async function login(role, id) {
    await page.goto(`/dashboard/${role}/login`);
    await page.getByLabel('Login ID', { exact: true }).fill(id);
    await page.getByLabel('Password', { exact: true }).fill('Preview123');
    await page.getByRole('button', { name: `Open ${role} dashboard` }).click();
    await expect(page).toHaveURL(new RegExp(`/dashboard/${role}$`));
  }
  await page.goto('/dashboard/customer');
  await expect(page).toHaveURL(/\/dashboard\/customer\/login$/);
  await login('customer', 'customer.demo');
  await expect(page.getByTestId('token-balance')).toHaveText('20');
  await expect(page.locator('.lunch-week-menu article')).toHaveCount(5);
  await page.screenshot({ path: testInfo.outputPath('customer.png'), fullPage: true });
  await page.getByRole('button', { name: 'Pause & extra tiffins', exact: true }).click();
  const extra = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Order more for one day' }) });
  await extra.getByLabel('Delivery date', { exact: true }).fill('2026-10-19');
  await extra.getByLabel('Total tiffins that day').fill('3');
  await extra.getByRole('button', { name: 'Save tiffin quantity' }).click();
  await expect(page.getByRole('status')).toContainText('Schedule saved');
  await expect(page.getByTestId('token-balance')).toHaveText('20');
  await login('customer', 'ananya.demo');
  await page.getByRole('button', { name: 'Pause & extra tiffins', exact: true }).click();
  const pause = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Pause your tiffin' }) });
  await pause.getByLabel('From date').fill('2026-10-19');
  await pause.getByLabel('Through date').fill('2026-10-21');
  await pause.getByRole('button', { name: 'Save pause' }).click();
  await expect(page.getByRole('status')).toContainText('Lunch paused');
  await login('admin', 'admin.demo');
  await expect(page.getByTestId('cooking-total')).toHaveText('4');
  await page.getByRole('button', { name: 'Weekly menu', exact: true }).click();
  const monday = page.locator('.lunch-week-menu section').first();
  await monday.getByLabel('Special dish / kitchen note').fill('Fresh kesari with Monday lunch.');
  await page.getByRole('button', { name: 'Publish weekly menu' }).click();
  await expect(page.getByRole('status')).toContainText('Weekly menu published');
  await page.getByRole('button', { name: 'Cooking plan', exact: true }).click();
  await page.getByRole('button', { name: 'Lock cooking list', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Cooking list locked');
  await page.screenshot({ path: testInfo.outputPath('admin.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await login('customer', 'customer.demo');
  await expect(page.locator('.lunch-week-menu')).toContainText('Fresh kesari');
  await page.getByRole('button', { name: 'Pause & extra tiffins', exact: true }).click();
  await pause.getByLabel('From date').fill('2026-10-19');
  await pause.getByLabel('Through date').fill('2026-10-19');
  await pause.getByRole('button', { name: 'Save pause' }).click();
  await expect(page.getByRole('status')).toContainText('locked');
  await login('admin', 'admin.demo');
  await page.getByRole('button', { name: 'Mark all fulfilled', exact: true }).click();
  await expect(page.getByRole('button', { name: 'All deliveries fulfilled', exact: true })).toBeDisabled();
  await page.reload();
  await expect(page.getByRole('button', { name: 'All deliveries fulfilled', exact: true })).toBeDisabled();
  await login('customer', 'customer.demo');
  await expect(page.getByTestId('token-balance')).toHaveText('17');
  await page.getByRole('button', { name: 'Rate my food', exact: true }).click();
  const review = page.locator('.lunch-reviews form').first();
  await review.getByLabel('Rating', { exact: true }).selectOption('4');
  await review.getByLabel('Your review').fill('Loved the fresh kesari.');
  await review.getByRole('button', { name: 'Send review', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('review is saved');
  await login('admin', 'admin.demo');
  await page.getByRole('button', { name: 'Customer reviews', exact: true }).click();
  await expect(page.locator('.lunch-reviews')).toContainText('Loved the fresh kesari.');
  await expect(page.locator('.lunch-reviews')).toContainText('4/5');
  await login('customer', 'ananya.demo');
  await expect(page.getByTestId('token-balance')).toHaveText('8');
});
