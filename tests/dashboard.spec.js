const { test, expect } = require('@playwright/test');

test('shop preview login, availability, orders and reopening settings', async ({ page }, testInfo) => {
  test.setTimeout(120000);
  await page.goto('/dashboard');
  await expect(page).toHaveURL(/\/dashboard\/login$/);
  const loginResponse = await page.request.get('/dashboard/login');
  expect(await loginResponse.text()).toContain('name="robots" content="noindex, nofollow"');
  await page.screenshot({ path: testInfo.outputPath('login.png'), fullPage: true });
  await page.getByLabel('Login ID', { exact: true }).fill('unknown');
  await page.getByLabel('Password', { exact: true }).fill('wrong');
  await page.getByRole('button', { name: 'Open demo dashboard' }).click();
  await expect(page.getByRole('status')).toContainText('Use one of the demo IDs');
  await page.getByRole('button', { name: 'Biryani & Curries biryani.demo' }).click();
  await page.getByRole('button', { name: 'Open demo dashboard' }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.locator('h1')).toHaveText('Biryani & Curries');
  await expect(page.locator('.partner-kpis article').first()).toContainText('6');
  await page.getByLabel('Report month').fill('2020-01');
  await expect(page.locator('.partner-kpis article').first().locator('strong')).toHaveText('0');
  const now = new Date();
  await page.getByLabel('Report month').fill(`${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('overview.png'), fullPage: true });
  await page.getByRole('button', { name: 'Products', exact: true }).click();
  const availability = page.getByRole('switch', { name: 'Availability for Curd Rice' });
  await expect(availability).toHaveAttribute('aria-checked', 'true');
  await availability.click();
  await expect(availability).toHaveAttribute('aria-checked', 'false');
  await page.reload();
  await page.getByRole('button', { name: 'Products', exact: true }).click();
  await expect(availability).toHaveAttribute('aria-checked', 'false');
  await page.getByRole('navigation', { name: 'Dashboard sections' }).getByRole('button', { name: /Orders/ }).click();
  await page.getByLabel('Status for BIRYANI-1041').selectOption('inprogress');
  await expect(page.getByLabel('Status for BIRYANI-1041')).toHaveValue('inprogress');
  const order = page.locator('.partner-order').filter({ hasText: '#BIRYANI-1041' });
  await order.getByLabel('Delivery tracking link').fill('javascript:alert(1)');
  await order.getByRole('button', { name: 'Save link' }).click();
  await expect(order.getByRole('status')).toContainText('valid HTTPS');
  await order.getByLabel('Delivery tracking link').fill('https://example.com/tracking/demo');
  await order.getByRole('button', { name: 'Save link' }).click();
  await expect(order.getByRole('link', { name: 'Open saved tracking' })).toHaveAttribute('href', 'https://example.com/tracking/demo');
  await page.getByLabel('Status for BIRYANI-1041').selectOption('sent');
  await page.getByRole('button', { name: 'Shop settings', exact: true }).click();
  await page.getByRole('switch', { name: 'Shop open' }).click();
  await expect(page.getByRole('heading', { name: 'Your shop is closed' })).toBeVisible();
  await page.getByLabel('Expected reopening').fill('2099-01-01T10:00');
  await page.getByLabel('Message for customers').fill('Back tomorrow morning.');
  await page.getByRole('button', { name: 'Save shop details' }).click();
  await expect(page.getByRole('status')).toContainText('Shop details saved');
  await page.reload();
  await expect(page.locator('.partner-account')).toContainText('Shop closed');
  await page.getByRole('button', { name: 'Shop settings', exact: true }).click();
  await expect(page.getByLabel('Expected reopening')).toHaveValue('2099-01-01T10:00');
  await expect(page.getByLabel('Message for customers')).toHaveValue('Back tomorrow morning.');
  await page.getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard\/login$/);
  await page.getByRole('button', { name: 'Sweets sweets.demo', exact: true }).click();
  await page.getByRole('button', { name: 'Open demo dashboard' }).click();
  await expect(page.locator('h1')).toHaveText('Sweets');
  await expect(page.locator('.partner-account')).toContainText('Shop open');
  await page.getByRole('button', { name: 'Products', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Availability for Motichoor laddu · 500 g' })).toHaveAttribute('aria-checked', 'true');
  await expect(page.getByRole('switch', { name: 'Availability for Curd Rice' })).toHaveCount(0);
  await page.getByRole('switch', { name: 'Availability for Motichoor laddu · 500 g' }).click();
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'This month at a glance' })).toBeVisible();
  await page.getByRole('button', { name: 'Products', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Availability for Motichoor laddu · 500 g' })).toHaveAttribute('aria-checked', 'true');
});
